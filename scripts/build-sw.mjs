import { readdir, readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";

async function walk(root, prefix = "") {
  const result = [];
  for (const item of await readdir(root, { withFileTypes: true })) {
    const relative = `${prefix}${item.name}`;
    if (item.isDirectory())
      result.push(...(await walk(path.join(root, item.name), `${relative}/`)));
    else if (item.name !== "sw.js") result.push(relative);
  }
  return result.sort();
}
// A CSP in built HTML also works on static hosts without configurable headers.
const htmlPath = "dist/index.html";
const html = await readFile(htmlPath, "utf8");
const csp =
  "default-src 'self'; script-src 'self' 'wasm-unsafe-eval'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; media-src 'self' blob:; connect-src 'self'; worker-src 'self' blob:; manifest-src 'self'; object-src 'none'; base-uri 'self'; form-action 'none'";
await writeFile(
  htmlPath,
  html.replace(
    "<head>",
    `<head>\n    <meta http-equiv="Content-Security-Policy" content="${csp}">`,
  ),
);
const files = await walk("dist");
const optional = files.filter(
  (file) =>
    file.startsWith("models/") ||
    file.startsWith("ort/") ||
    file.endsWith(".wasm"),
);
const core = files.filter((file) => !optional.includes(file));
const hash = createHash("sha256");
for (const file of files) {
  hash.update(file);
  hash.update(await readFile(path.join("dist", file)));
}
const version = hash.digest("hex").slice(0, 16);
const modelHash = createHash("sha256");
for (const file of optional) {
  modelHash.update(file);
  modelHash.update(await readFile(path.join("dist", file)));
}
const modelVersion = modelHash.digest("hex").slice(0, 16);
await writeFile(
  "dist/sw.js",
  `/* Generated by ExamGuard: assets only, never inspection data. */
const PREFIX = 'examguard:' + self.registration.scope + ':';
const CACHE = PREFIX + '${version}';
const MODEL_CACHE = PREFIX + 'model:${modelVersion}';
const FILES = ${JSON.stringify(core)}.map(file => new URL(file, self.registration.scope).href);
const OPTIONAL = ${JSON.stringify(optional)}.map(file => new URL(file, self.registration.scope).href);
const INDEX = new URL('index.html', self.registration.scope).href;
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', event => {
  event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(key => key.startsWith(PREFIX) && key !== CACHE && key !== MODEL_CACHE).map(key => caches.delete(key)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', event => {
  if (event.request.method !== 'GET') return;
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin) return;
  url.search = ''; url.hash = '';
  const key = url.href === self.registration.scope ? INDEX : url.href;
  if (!FILES.includes(key) && !OPTIONAL.includes(key)) return;
  const isModel = OPTIONAL.includes(key);
  event.respondWith(caches.open(isModel ? MODEL_CACHE : CACHE).then(async cache => {
    const saved = await cache.match(key);
    if (saved) return saved;
    const response = await fetch(event.request);
    if (response.ok && response.status === 200) {
      try { await cache.put(key, response.clone()); } catch { /* Quota failure must not block a live request. */ }
    }
    return response;
  }));
});
self.addEventListener('message', event => {
  if (event.data !== 'CACHE_STATUS' || !event.ports[0]) return;
  event.waitUntil(caches.open(CACHE).then(async cache => {
    const matches = await Promise.all(FILES.map(file => cache.match(file)));
    event.ports[0].postMessage({ ready: matches.every(Boolean), version: '${version}' });
  }));
});
`,
);
console.log(
  `Precache: ${core.length} core assets; ${optional.length} model/runtime assets cached only on request; ${version}.`,
);
